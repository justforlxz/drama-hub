// Package jellyfin 维护 Jellyfin 的「一分类一媒体库」（ADR-0012）。
//
// 为什么是一分类一库：Jellyfin 只把**库根的直接子目录**当剧集。库根挂在挂载根上时，
// 分类目录会被认成 Series、剧目录退化成普通 Folder（现网实测：58 个分类成了 58 部
// Series、1436 个剧目录失效）。所以库根必须收窄到 `<挂载根>/<分类>`，一个分类一个库。
//
// 本包只做四件可观察的事：
//
//   - 按分类差异建库（幂等：已存在的自管库一律不动）；
//   - 分类开关关掉的库在下一轮删掉（幂等、失败重试），分类消失的孤儿库只报告；
//   - 有变化时触发一次 Jellyfin 扫描；
//   - 把失败原因写进内存状态（不落库），供状态页显示。
//
// 依赖方向（docs/DEV-STANDARDS.md「代码组织」）：只依赖标准库 + 注入的三个函数
// （读配置、列分类、读分类开关）。不 import store / vfs / web —— 接口由消费方定义、装配根接上，
// 与 scheduler.Syncer、web.Schedule 同一条规矩。失败隔离也是这一句的推论：
// 本包的任何错误都不进入同步轮的状态，Jellyfin 挂了同步、WebDAV、播放照常。
